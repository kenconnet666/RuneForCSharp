#!/usr/bin/env node
// 从 vue-tsx-pro 主题编辑器用的 Radix 色阶（packages/ui/src/theme-customize/palette.ts 列出的品牌色、中性色，值取自它依赖的 @radix-ui/colors）
// 生成三个库的 RadixScales（ThemeCustomize/RadixScales.g.cs）：每个色阶亮色、暗色各 12 级。
// 用法：node tools/theme-gen/theme-gen.mjs [--check] [--vue <路径>]
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { writeOutputs } from '../lib/output.mjs';
import { openVue } from '../lib/vue.mjs';

const LIBRARIES = [
  { namespace: 'Rune.Avalonia', path: 'avalonia/src/Rune.Avalonia/ThemeCustomize/RadixScales.g.cs' },
  { namespace: 'Rune.Wpf', path: 'wpf/src/Rune.Wpf/ThemeCustomize/RadixScales.g.cs' },
  { namespace: 'Rune.WinForms', path: 'winforms/src/Rune.WinForms/ThemeCustomize/RadixScales.g.cs' },
];

/** palette.ts 里一张表的色阶名（按表里的顺序）：`  tomato: [tomato, tomatoDark],` */
function tableNames(source, table) {
  const start = source.indexOf(`const ${table} = {`);
  if (start < 0) throw new Error(`palette.ts 里找不到 ${table}`);
  const end = source.indexOf('\n}', start);
  const names = [...source.slice(start, end).matchAll(/^\s+(\w+): \[\w+, \w+Dark\],$/gm)].map(([, name]) => name);
  if (names.length === 0) throw new Error(`palette.ts 的 ${table} 是空的`);
  return names;
}

/** 一个色阶的 12 级 */
function steps(colors, key, name) {
  const scale = colors[key];
  if (!scale) throw new Error(`@radix-ui/colors 里没有 ${key}`);
  return Array.from({ length: 12 }, (_, index) => {
    const value = scale[`${name}${index + 1}`];
    if (!/^#[0-9a-f]{6}$/i.test(value ?? '')) throw new Error(`${key} 的第 ${index + 1} 级不是 #rrggbb：${value}`);
    return value.toLowerCase();
  });
}

function file(namespace, accents, neutrals, version) {
  const line = ([name, light, dark]) => `        ["${name}"] = (["${light.join('", "')}"], ["${dark.join('", "')}"]),`;
  return [
    '// <auto-generated>',
    '// 由 tools/theme-gen/theme-gen.mjs 从 vue-tsx-pro 的 theme-customize/palette.ts 与 @radix-ui/colors 生成，不要手改。',
    `// 色阶取自 @radix-ui/colors ${version}（MIT License），见 licenses/radix-colors.txt。`,
    '// </auto-generated>',
    '',
    `namespace ${namespace};`,
    '',
    '/// <summary>主题编辑器的 Radix 色阶：名字 → 亮色、暗色各 12 级（#rrggbb，第 1 级最浅）。</summary>',
    'static class RadixScales',
    '{',
    '    /// <summary>品牌色，按色相排列（同 Radix 文档的顺序）。</summary>',
    '    public static readonly Dictionary<string, (string[] Light, string[] Dark)> Accents = new()',
    '    {',
    ...accents.map(line),
    '    };',
    '',
    '    /// <summary>中性色（各带一点色相，与品牌色搭配）。</summary>',
    '    public static readonly Dictionary<string, (string[] Light, string[] Dark)> Neutrals = new()',
    '    {',
    ...neutrals.map(line),
    '    };',
    '}',
    '',
  ].join('\n');
}

const { values: options } = parseArgs({ options: { check: { type: 'boolean', default: false }, vue: { type: 'string' } } });

const vue = await openVue(options.vue);
try {
  const source = readFileSync(join(vue.src, 'theme-customize/palette.ts'), 'utf8');
  const require = createRequire(join(vue.root, 'packages/ui/package.json'));
  const colors = require('@radix-ui/colors');
  const version = JSON.parse(readFileSync(require.resolve('@radix-ui/colors/package.json'), 'utf8')).version;
  const scales = (table) => tableNames(source, table).map((name) => [name, steps(colors, name, name), steps(colors, `${name}Dark`, name)]);
  const accents = scales('ACCENT_TABLE');
  const neutrals = scales('NEUTRAL_TABLE');
  const outputs = LIBRARIES.map(({ namespace, path }) => ({ path, content: file(namespace, accents, neutrals, version) }));
  process.exitCode = writeOutputs(outputs, { check: options.check, commit: vue.commit, command: 'node tools/theme-gen/theme-gen.mjs' });
} catch (error) {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
} finally {
  vue.close();
}
