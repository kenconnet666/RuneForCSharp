// WPF 的输出：Tokens.g.xaml（不随主题变的 token）、Themes/<主题>.g.xaml（每套主题一份，RuneTheme 换的就是它）、
// RuneTheme.g.cs（内置主题清单）、CubicBezierEase.g.cs（缓动 token）
import { argbHex } from '../lib/css.mjs';
import { comment, describe, escape, FONT_WEIGHTS, HEADER, number, summary, themeTitle, timeSpan } from './format.mjs';

const DIR = 'wpf/src/Rune.Wpf/Config/Generated';
const NAMESPACES = [
  'xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
  'xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
  'xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006"',
  'xmlns:po="http://schemas.microsoft.com/winfx/2006/xaml/presentation/options"',
  'xmlns:sys="clr-namespace:System;assembly=System.Runtime"',
  'xmlns:rune="clr-namespace:Rune.Wpf"',
  'mc:Ignorable="po"',
];

/**
 * WPF 没有多层的 box-shadow：取最显眼的一层（模糊最大、不透明度不低于 0.05 的）做 DropShadowEffect，spread 丢掉。
 * 各层的完整数据 WinForms 的输出里有，要精确的阴影时再做专门的绘制
 */
function dropShadow(key, layers) {
  if (!layers.length) return `<x:Null x:Key="${key}" />`;
  const visible = layers.filter((layer) => layer.color.a >= 0.05);
  const layer = (visible.length ? visible : layers).reduce((best, l) => (l.blur > best.blur ? l : best));
  const depth = Math.hypot(layer.x, layer.y);
  const direction = ((Math.atan2(-layer.y, layer.x) * 180) / Math.PI + 360) % 360;
  const color = argbHex({ ...layer.color, a: 1 });
  return `<DropShadowEffect x:Key="${key}" po:Freeze="True" BlurRadius="${number(layer.blur)}" ShadowDepth="${number(depth)}" Direction="${number(direction)}" Color="${color}" Opacity="${number(layer.color.a)}" />`;
}

function resources(entry) {
  const key = `Rune.${entry.name}`;
  const { value } = entry;
  switch (entry.kind) {
    case 'color': {
      const brushKey = `Rune.Brush.${entry.name.slice('Color.'.length)}`;
      return [`<Color x:Key="${key}">${argbHex(value)}</Color>`, `<SolidColorBrush x:Key="${brushKey}" po:Freeze="True" Color="${argbHex(value)}" />`];
    }
    case 'font':
      return [`<FontFamily x:Key="${key}">${escape(value.join(', '))}</FontFamily>`];
    case 'length':
      return [`<sys:Double x:Key="${key}">${number(value.value)}</sys:Double>`];
    case 'number':
      if (entry.group === 'fontWeights') {
        if (!FONT_WEIGHTS[value]) throw new Error(`${key}：WPF 没有字重 ${value} 对应的名字`);
        return [`<FontWeight x:Key="${key}">${FONT_WEIGHTS[value]}</FontWeight>`];
      }
      return [`<sys:Double x:Key="${key}">${number(value)}</sys:Double>`];
    case 'shadow':
      return [dropShadow(key, value)];
    case 'duration':
      return [`<sys:TimeSpan x:Key="${key}">${timeSpan(value)}</sys:TimeSpan>`];
    case 'easing':
      return [`<x:Static x:Key="${key}" Member="rune:CubicBezierEase.${entry.name.slice('Easing.'.length)}" />`];
    default:
      throw new Error(`${key}：WPF 没有 ${entry.kind} 的写法`);
  }
}

function dictionary(title, entries) {
  const lines = [comment(HEADER), comment(title), `<ResourceDictionary ${NAMESPACES.join('\n                    ')}>`];
  let group;
  for (const entry of entries) {
    if (entry.group !== group) {
      group = entry.group;
      lines.push('', `  ${comment(group)}`);
    }
    lines.push(`  ${comment(describe(entry))}`, ...resources(entry).map((line) => `  ${line}`));
  }
  lines.push('</ResourceDictionary>', '');
  return lines.join('\n');
}

function themeList(model) {
  return [
    '// <auto-generated />',
    `// ${HEADER}`,
    'namespace Rune.Wpf;',
    '',
    'public partial class RuneTheme',
    '{',
    '    /// <summary>全部内置主题，顺序同 vue-tsx-pro 的 builtinThemes（主题切换器按这个顺序列出）。</summary>',
    '    public static IReadOnlyList<BuiltinTheme> BuiltinThemes { get; } =',
    '    [',
    ...model.themes.map((theme) => `        new("${theme.name}", "${theme.label}", ${theme.colorScheme === 'dark'}, new("pack://application:,,,/Rune.Wpf;component/Config/Generated/Themes/${theme.id}.g.xaml")),`),
    '    ];',
    '}',
    '',
  ].join('\n');
}

function easings(model) {
  const entries = model.base.filter((entry) => entry.kind === 'easing');
  return [
    '// <auto-generated />',
    `// ${HEADER}`,
    'namespace Rune.Wpf;',
    '',
    'public sealed partial class CubicBezierEase',
    '{',
    ...entries.flatMap((entry) => [
      `    ${summary(`${entry.doc || entry.key}：${entry.raw}（已冻结）。`)}`,
      `    public static CubicBezierEase ${entry.name.slice('Easing.'.length)} => Builtin.${entry.name.slice('Easing.'.length)};`,
      '',
    ]),
    '    /// <summary>放在嵌套类里，等本类的依赖属性注册完才创建：分部类各文件的静态字段谁先初始化是不确定的。</summary>',
    '    static class Builtin',
    '    {',
    ...entries.map((entry) => `        public static readonly CubicBezierEase ${entry.name.slice('Easing.'.length)} = Frozen(${entry.value.map(number).join(', ')});`),
    '    }',
    '}',
    '',
  ].join('\n');
}

export function wpf(model) {
  return [
    { path: `${DIR}/Tokens.g.xaml`, content: dictionary('不随主题变的 token；em 类的长度是系数，px、rem 类已换成设备无关像素', model.base) },
    ...model.themes.map((theme) => ({
      path: `${DIR}/Themes/${theme.id}.g.xaml`,
      content: dictionary(`${themeTitle(theme)}：随主题变的 token（${model.themed.join('、')}）；阴影取最显眼的一层做 DropShadowEffect`, theme.entries),
    })),
    { path: `${DIR}/RuneTheme.g.cs`, content: themeList(model) },
    { path: `${DIR}/CubicBezierEase.g.cs`, content: easings(model) },
  ];
}
