// Avalonia、WPF 共用的 ThemeKeys.g.cs：每个 token 资源键一个常量，外加查不到资源时的默认值。
// 代码里查资源、设资源引用都用这些常量，拼错了编译就报；默认值从这里出，组件里不再各写一份数字
import { number, summary } from './format.mjs';

/** 默认值取哪套主题：随主题变的组（圆角、阴影……）取亮色 */
const defaultTheme = (model) => model.themes.find((theme) => theme.name === 'light') ?? model.themes[0];

/**
 * 资源键与默认值：每个 token 一项，颜色多一项画刷（Rune.Brush.*），带取整的长度多一项步长（<键>Round）。
 * fallback 是 C# 表达式，null 表示没有默认值（颜色、阴影、字体：没合并主题时本来就画不对，不假装有值）
 */
function keysOf(entries, platform) {
  return entries.flatMap((entry) => {
    const [group, name] = entry.name.split('.');
    const { value } = entry;
    switch (entry.kind) {
      case 'color':
        return [
          { group, name, entry, fallback: null },
          { group: 'Brush', name, entry, fallback: null },
        ];
      case 'length':
        return [
          { group, name, entry, fallback: `${number(value.value)}d` },
          ...(value.round ? [{ group, name: `${name}Round`, entry, fallback: `${number(value.round)}d` }] : []),
        ];
      case 'number':
        return [{ group, name, entry, fallback: entry.group === 'fontWeights' ? platform.fontWeight(value) : `${number(value)}d` }];
      case 'duration':
        return [{ group, name, entry, fallback: `global::System.TimeSpan.FromMilliseconds(${number(value)})` }];
      case 'easing':
        return [{ group, name, entry, fallback: platform.easing(name, value) }];
      default:
        return [{ group, name, entry, fallback: null }];
    }
  });
}

/**
 * @param model token 模型
 * @param platform `{ namespace, path, lookup, fontWeight(value), easing(name, [x1, y1, x2, y2]) }`：lookup 是查资源的方法（文档里引用）
 */
export function themeKeys(model, platform) {
  const keys = keysOf([...model.base, ...defaultTheme(model).entries], platform);
  const groups = Map.groupBy(keys, (key) => key.group);
  const lines = [
    '// <auto-generated />',
    '#nullable enable',
    '// 由 tools/token-gen 生成，不要手改；改了 vue-tsx-pro 的 token 后运行 node tools/token-gen/token-gen.mjs',
    `namespace ${platform.namespace};`,
    '',
    '/// <summary>',
    '/// 主题资源（token）的键：代码里查资源、设资源引用用这些常量，拼错了编译就报。',
    `/// 用 ${platform.lookup} 查，查不到（没合并 RuneTheme）时取 <see cref="Fallback"/>：不随主题变的取 token 的值，随主题变的长度取亮色主题的，`,
    '/// 颜色、阴影、字体没有默认值。',
    '/// </summary>',
    'public static class ThemeKeys',
    '{',
  ];
  for (const [group, members] of groups) {
    lines.push(`    /// <summary>Rune.${group}.*</summary>`, `    public static class ${group}`, '    {');
    for (const { name, entry } of members) {
      lines.push(`        ${summary(entryDoc(entry, group, name))}`, `        public const string ${name} = "Rune.${group}.${name}";`);
    }
    lines.push('    }', '');
  }
  lines.push(
    '    /// <summary>查不到资源时的默认值；不是 token 的键、没有默认值的 token 为 null。</summary>',
    '    /// <param name="key">资源键。</param>',
    '    public static object? Fallback(string key) => key switch',
    '    {',
    ...keys.filter((key) => key.fallback).map((key) => `        ${key.group}.${key.name} => ${key.fallback},`),
    '        _ => null,',
    '    };',
    '}',
    '',
  );
  return { path: platform.path, content: lines.join('\n') };
}

function entryDoc(entry, group, name) {
  const note = group === 'Brush' ? '（画刷）' : name.endsWith('Round') && entry.value?.round ? '（取整的步长，设备无关像素）' : '';
  const unit = entry.kind === 'length' && !note ? (entry.value.unit === 'em' ? '（em 系数）' : '（设备无关像素）') : '';
  return `${entry.key} = ${entry.raw}${unit}${note}${entry.doc ? `：${entry.doc}` : ''}`;
}
