// WinForms 的输出：Tokens.g.cs（不随主题变的常量）、Themes.g.cs（16 套内置主题随主题变的数据）、Easing.g.cs（缓动 token）。
// WinForms 没有资源系统，主题是普通的 C# 对象，运行时的信号与作用域建在它上面（DESIGN §4、§10）
import { describe, float, HEADER, number, summary } from './format.mjs';
import { GROUPS, pascal } from './model.mjs';

const DIR = 'winforms/src/Rune.WinForms/Config/Generated';
const PREAMBLE = ['// <auto-generated />', `// ${HEADER}`, 'namespace Rune.WinForms;', ''];

const csString = (text) => `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const color = ({ r, g, b, a }) => `Color.FromArgb(${Math.round(a * 255)}, ${r}, ${g}, ${b})`;

/** 随主题变的一项：C# 的类型与取值 */
function themed(entry) {
  switch (entry.kind) {
    case 'color':
      return { type: 'Color', value: color(entry.value) };
    case 'shadow':
      return {
        type: 'IReadOnlyList<ShadowLayer>',
        value: `[${entry.value.map((l) => `new(${float(l.x)}, ${float(l.y)}, ${float(l.blur)}, ${float(l.spread)}, ${color(l.color)}${l.inset ? ', Inset: true' : ''})`).join(', ')}]`,
      };
    case 'font':
      return { type: 'IReadOnlyList<string>', value: `[${entry.value.map(csString).join(', ')}]` };
    case 'length':
      return { type: 'float', value: float(entry.value.value) };
    default:
      throw new Error(`Rune.${entry.name}：WinForms 的主题里没有 ${entry.kind} 的写法`);
  }
}

function tokens(model) {
  const groups = Map.groupBy(model.base.filter((entry) => entry.kind !== 'easing'), (entry) => entry.group);
  const lines = [
    ...PREAMBLE,
    '/// <summary>',
    '/// 不随主题变的 token（vue-tsx-pro 的 tokens.ts）。em 类的长度（间距、圆角、控件高度、字间距）是系数，乘以字号；',
    '/// px、rem 类已换成设备无关像素，绘制时按 DeviceDpi 换算。缓动在 <see cref="Easing"/> 上。',
    '/// </summary>',
    'public static class Tokens',
    '{',
  ];
  for (const [group, entries] of groups) {
    lines.push(`    ${summary(`${group}（${entries.length} 个）。`)}`, `    public static class ${GROUPS[group].name}`, '    {');
    for (const entry of entries) {
      lines.push(`        ${summary(describe(entry))}`);
      const name = entry.name.split('.')[1];
      if (entry.kind === 'duration') lines.push(`        public static readonly TimeSpan ${name} = TimeSpan.FromMilliseconds(${number(entry.value)});`);
      else if (entry.group === 'fontWeights') lines.push(`        public const int ${name} = ${entry.value};`);
      else lines.push(`        public const float ${name} = ${float(entry.kind === 'length' ? entry.value.value : entry.value)};`);
      if (entry.kind === 'length' && entry.value.round)
        lines.push(`        ${summary(`${name} 取整的步长（设备无关像素）：按字号算出的值取整到它的倍数。`)}`, `        public const float ${name}Round = ${float(entry.value.round)};`);
    }
    lines.push('    }', '');
  }
  lines.splice(-1, 1, '}', '');
  return lines.join('\n');
}

function themes(model) {
  const [first] = model.themes;
  const groups = Map.groupBy(first.entries, (entry) => entry.group);
  const lines = [...PREAMBLE];
  // 每组一个类：属性是这组的 token，说明取自亮色
  for (const [group, entries] of groups) {
    lines.push(`${summary(`一套主题的 ${group}（${entries.length} 个）。`)}`, `public sealed class Theme${pascal(group)}`, '{');
    for (const entry of entries) lines.push(`    ${summary(describe(entry))}`, `    public required ${themed(entry).type} ${pascal(entry.key)} { get; init; }`, '');
    lines.splice(-1, 1, '}', '');
  }
  lines.push(
    `${summary(`一套内置主题随主题变的 token（${model.themed.join('、')}）；其余 token 不随主题变，见 Tokens。`)}`,
    'public sealed class ThemeTokens',
    '{',
    '    /// <summary>名字，同 vue-tsx-pro 的 builtinThemes（light、high-contrast……）。</summary>',
    '    public required string Name { get; init; }',
    '',
    '    /// <summary>中文名。</summary>',
    '    public required string Label { get; init; }',
    '',
    '    /// <summary>是不是暗色主题。</summary>',
    '    public required bool IsDark { get; init; }',
    ...[...groups.keys()].flatMap((group) => ['', `    ${summary(group)}`, `    public required Theme${pascal(group)} ${pascal(group)} { get; init; }`]),
    '}',
    '',
    '/// <summary>vue-tsx-pro 的 16 套内置主题。</summary>',
    'public static class BuiltinThemes',
    '{',
  );
  for (const theme of model.themes) {
    lines.push(
      `    ${summary(`${theme.label}（${theme.colorScheme === 'dark' ? '暗色' : '亮色'}）。`)}`,
      `    public static readonly ThemeTokens ${theme.id} = new()`,
      '    {',
      `        Name = ${csString(theme.name)},`,
      `        Label = ${csString(theme.label)},`,
      `        IsDark = ${theme.colorScheme === 'dark'},`,
    );
    for (const [group, entries] of Map.groupBy(theme.entries, (entry) => entry.group)) {
      lines.push(`        ${pascal(group)} = new()`, '        {');
      for (const entry of entries) lines.push(`            ${pascal(entry.key)} = ${themed(entry).value},`);
      lines.push('        },');
    }
    lines.push('    };', '');
  }
  lines.push(
    '    /// <summary>全部内置主题，顺序同 vue-tsx-pro 的 builtinThemes（主题切换器按这个顺序列出）。</summary>',
    `    public static IReadOnlyList<ThemeTokens> All { get; } = [${model.themes.map((theme) => theme.id).join(', ')}];`,
    '}',
    '',
  );
  return lines.join('\n');
}

function easings(model) {
  const entries = model.base.filter((entry) => entry.kind === 'easing');
  return [
    ...PREAMBLE,
    'public sealed partial class Easing',
    '{',
    ...entries.flatMap((entry) => [
      `    ${summary(`${entry.doc || entry.key}：${entry.raw}。`)}`,
      `    public static readonly Easing ${entry.name.split('.')[1]} = new(${entry.value.map(number).join(', ')});`,
      '',
    ]).slice(0, -1),
    '}',
    '',
  ].join('\n');
}

export function winforms(model) {
  return [
    { path: `${DIR}/Tokens.g.cs`, content: tokens(model) },
    { path: `${DIR}/Themes.g.cs`, content: themes(model) },
    { path: `${DIR}/Easing.g.cs`, content: easings(model) },
  ];
}
