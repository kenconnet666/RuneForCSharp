// Avalonia 的输出：Tokens.g.axaml（不随主题变的 token + 每套内置主题一个 ThemeDictionary）与 RuneThemeVariants.g.cs
import { argbHex } from '../lib/css.mjs';
import { comment, customThemes, describe, escape, FONT_WEIGHTS, HEADER, number, themeTitle, timeSpan } from './format.mjs';

const DIR = 'avalonia/src/Rune.Avalonia/Config/Generated';

function shadow(layers) {
  if (!layers.length) return 'none';
  return layers.map((l) => `${l.inset ? 'inset ' : ''}${number(l.x)} ${number(l.y)} ${number(l.blur)} ${number(l.spread)} ${argbHex(l.color)}`).join(', ');
}

/** 一个 token 的资源元素（颜色出两个：Color 与 SolidColorBrush） */
function resources(entry) {
  const key = `Rune.${entry.name}`;
  const { value } = entry;
  switch (entry.kind) {
    case 'color': {
      const brushKey = `Rune.Brush.${entry.name.slice('Color.'.length)}`;
      return [`<Color x:Key="${key}">${argbHex(value)}</Color>`, `<SolidColorBrush x:Key="${brushKey}" Color="${argbHex(value)}" />`];
    }
    case 'font':
      return [`<FontFamily x:Key="${key}">${escape(value.join(', '))}</FontFamily>`];
    case 'length':
      return [`<x:Double x:Key="${key}">${number(value.value)}</x:Double>`];
    case 'number':
      if (entry.group === 'fontWeights') {
        if (!FONT_WEIGHTS[value]) throw new Error(`${key}：Avalonia 没有字重 ${value} 对应的名字`);
        return [`<FontWeight x:Key="${key}">${FONT_WEIGHTS[value]}</FontWeight>`];
      }
      return [`<x:Double x:Key="${key}">${number(value)}</x:Double>`];
    case 'shadow':
      return [`<BoxShadows x:Key="${key}">${shadow(value)}</BoxShadows>`];
    case 'duration':
      return [`<sys:TimeSpan x:Key="${key}">${timeSpan(value)}</sys:TimeSpan>`];
    case 'easing':
      return [`<SplineEasing x:Key="${key}" X1="${number(value[0])}" Y1="${number(value[1])}" X2="${number(value[2])}" Y2="${number(value[3])}" />`];
    default:
      throw new Error(`${key}：Avalonia 没有 ${entry.kind} 的写法`);
  }
}

/** 一组条目：每组前写组名，每项前写取值与说明（em 类注明是系数） */
function block(entries, indent, withDocs) {
  const lines = [];
  let group;
  for (const entry of entries) {
    if (entry.group !== group) {
      group = entry.group;
      lines.push('', `${indent}${comment(`${group}`)}`);
    }
    if (withDocs) lines.push(`${indent}${comment(describe(entry))}`);
    for (const line of resources(entry)) lines.push(`${indent}${line}`);
  }
  return lines;
}

function themeKey(theme) {
  if (theme.name === 'light') return 'Light';
  if (theme.name === 'dark') return 'Dark';
  return `{x:Static rune:RuneThemeVariants.${theme.id}}`;
}

function axaml(model) {
  const lines = [
    comment(HEADER),
    comment('em 类的长度（间距、圆角、控件高度、字间距）是系数，乘以元素的字号；px、rem 类已换成设备无关像素'),
    comment(`跳过的 token：${Object.entries(model.skipped).map(([key, why]) => `${key}（${why}）`).join('；')}`),
    '<ResourceDictionary xmlns="https://github.com/avaloniaui"',
    '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
    '                    xmlns:sys="clr-namespace:System;assembly=System.Runtime"',
    '                    xmlns:rune="clr-namespace:Rune.Avalonia">',
    ...block(model.base, '  ', true),
    '',
    `  ${comment(`随主题变的组（${model.themed.join('、')}）：每套内置主题一份；说明只写在亮色里`)}`,
    '  <ResourceDictionary.ThemeDictionaries>',
  ];
  for (const theme of model.themes) {
    lines.push(`    ${comment(themeTitle(theme))}`);
    lines.push(`    <ResourceDictionary x:Key="${themeKey(theme)}">`);
    lines.push(...block(theme.entries, '      ', theme.name === 'light').filter((line, i) => i > 0 || line));
    lines.push('    </ResourceDictionary>');
  }
  lines.push('  </ResourceDictionary.ThemeDictionaries>', '</ResourceDictionary>', '');
  return lines.join('\n');
}

function variants(model) {
  const custom = customThemes(model);
  const all = model.themes.map((theme) => (theme.name === 'light' ? 'ThemeVariant.Light' : theme.name === 'dark' ? 'ThemeVariant.Dark' : theme.id));
  return [
    '// <auto-generated />',
    `// ${HEADER}`,
    'using Avalonia.Styling;',
    '',
    'namespace Rune.Avalonia;',
    '',
    '/// <summary>',
    '/// vue-tsx-pro 的内置主题对应的主题变体：亮色、暗色用 Avalonia 自带的，其余各是一个自定义变体，',
    '/// 主题字典里没有的资源回落到它所属的亮色或暗色。用法：<c>RequestedThemeVariant="{x:Static rune:RuneThemeVariants.Paper}"</c>，',
    '/// 局部主题用 <c>ThemeVariantScope</c>。',
    '/// </summary>',
    'public static class RuneThemeVariants',
    '{',
    ...custom.flatMap((theme) => [
      `    /// <summary>${theme.label}（${theme.colorScheme === 'dark' ? '暗色' : '亮色'}）。</summary>`,
      `    public static readonly ThemeVariant ${theme.id} = new("${theme.name}", ThemeVariant.${theme.colorScheme === 'dark' ? 'Dark' : 'Light'});`,
      '',
    ]),
    '    /// <summary>全部内置主题，顺序同 vue-tsx-pro 的 builtinThemes（主题切换器按这个顺序列出）。</summary>',
    `    public static IReadOnlyList<ThemeVariant> All { get; } = [${all.join(', ')}];`,
    '}',
    '',
  ].join('\n');
}

export function avalonia(model) {
  return [
    { path: `${DIR}/Tokens.g.axaml`, content: axaml(model) },
    { path: `${DIR}/RuneThemeVariants.g.cs`, content: variants(model) },
  ];
}
