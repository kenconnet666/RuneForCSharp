#!/usr/bin/env node
// 生成 Lucide 全集：三个库各写一份 Base/Icon/Lucide.g.cs，路径归一成 M、L、C、Z（svg.mjs）；
// Lucide 的许可（ISC，部分图标派生自 Feather，MIT）复制到 licenses/lucide.txt。
// 图标数据用 vue-tsx-pro 装好的 @lucide/icons（版本跟着 vue-tsx-pro 走），本仓库不装 node 包。
// 用法：node tools/icons-gen/icons-gen.mjs [--check] [--vue <路径>]
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { writeOutputs } from '../lib/output.mjs';
import { openVue } from '../lib/vue.mjs';
import { normalize } from './svg.mjs';

const LIBRARIES = [
  { namespace: 'Rune.Avalonia', path: 'avalonia/src/Rune.Avalonia/Base/Icon/Lucide.g.cs' },
  { namespace: 'Rune.Wpf', path: 'wpf/src/Rune.Wpf/Base/Icon/Lucide.g.cs' },
  { namespace: 'Rune.WinForms', path: 'winforms/src/Rune.WinForms/Base/Icon/Lucide.g.cs' },
];

/** Lucide 的图标名 → C# 名字，同 Lucide 的 JS 导出名：circle-x → CircleX，trash-2 → Trash2 */
const pascal = (name) => name.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());

/** vue-tsx-pro 组件库装的 @lucide/icons：版本、许可与全部图标（按图标名去重，每个图标只取一份） */
async function lucide(vue) {
  const dir = join(vue.root, 'packages/ui/node_modules/@lucide/icons');
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const module = await import(pathToFileURL(join(dir, pkg.main)).href);
  const icons = new Map();
  for (const icon of Object.values(module.default ?? module)) {
    if (icon && Array.isArray(icon.node) && !icons.has(icon.name)) icons.set(icon.name, icon);
  }
  return { version: pkg.version, license: readFileSync(join(dir, 'LICENSE'), 'utf8'), icons: [...icons.values()].sort((a, b) => a.name.localeCompare(b.name)) };
}

function file(namespace, version, icons) {
  const aliasCount = icons.reduce((n, icon) => n + icon.aliases.length, 0);
  const lines = [
    '// <auto-generated />',
    `// 由 tools/icons-gen 从 Lucide（@lucide/icons ${version}，取自 vue-tsx-pro 的依赖）生成，不要手改；运行 node tools/icons-gen/icons-gen.mjs`,
    '// Lucide 是 ISC 许可，其中派生自 Feather 的图标是 MIT 许可，全文见仓库的 licenses/lucide.txt（随包分发）',
    `namespace ${namespace};`,
    '',
    '/// <summary>',
    `/// Lucide 图标全集（${icons.length} 个），名字同 Lucide 的 JS 导出名：<c>Lucide.CircleX</c>、<c>Lucide.ArrowRight</c>。`,
    '/// 24×24 的描边路径，已归一成绝对坐标的 M、L、C、Z；少数图标另有填充的部分（<see cref="IconData.FillPath"/>）。',
    `/// 每个图标第一次用到时才创建。Lucide 改过名的 ${aliasCount} 个旧名是标了 Obsolete 的转发属性，提示新名字。`,
    '/// </summary>',
    'public static class Lucide',
    '{',
  ];
  for (const icon of icons) {
    const args = [`"${icon.name}"`, `"${icon.path}"`, ...(icon.fillPath ? [`"${icon.fillPath}"`] : [])].join(', ');
    lines.push(`    /// <summary>${icon.name}${icon.aliases.length ? `（旧名 ${icon.aliases.join('、')}）` : ''}。</summary>`);
    lines.push(`    public static IconData ${icon.id} => field ??= new(${args});`);
  }
  for (const icon of icons) {
    for (const alias of icon.aliases) {
      lines.push(`    /// <summary>${alias}：Lucide 已改名为 ${icon.name}。</summary>`);
      lines.push(`    [Obsolete("Lucide 已改名为 ${icon.name}，用 ${icon.id}")]`);
      lines.push(`    public static IconData ${pascal(alias)} => ${icon.id};`);
    }
  }
  lines.push('}', '');
  return lines.join('\n');
}

const { values: options } = parseArgs({
  options: {
    check: { type: 'boolean', default: false },
    vue: { type: 'string' },
  },
});

const vue = await openVue(options.vue);
try {
  const source = await lucide(vue);
  const names = new Set();
  const claim = (id, owner) => {
    if (!/^[A-Z][A-Za-z0-9]*$/.test(id)) throw new Error(`${owner} 的名字 ${id} 不是合法的 C# 标识符`);
    if (names.has(id)) throw new Error(`名字 ${id} 重复（${owner}）`);
    names.add(id);
  };
  const icons = source.icons.map((icon) => {
    const id = pascal(icon.name);
    claim(id, icon.name);
    try {
      return { id, name: icon.name, aliases: icon.aliases ?? [], ...normalize(icon.node) };
    } catch (error) {
      throw new Error(`${icon.name}：${error.message}`);
    }
  });
  // 旧名转成 C# 名字后可能与新名相同（arrow-down-01 与 arrow-down-0-1 都是 ArrowDown01，Lucide 的 JS 导出也是同一个）：这种不用转发
  for (const icon of icons) {
    icon.aliases = icon.aliases.filter((alias) => pascal(alias) !== icon.id);
    for (const alias of icon.aliases) claim(pascal(alias), `${icon.name} 的旧名 ${alias}`);
  }
  const outputs = [
    ...LIBRARIES.map(({ namespace, path }) => ({ path, content: file(namespace, source.version, icons) })),
    { path: 'licenses/lucide.txt', content: source.license },
  ];
  process.exitCode = writeOutputs(outputs, { check: options.check, commit: vue.commit, command: 'node tools/icons-gen/icons-gen.mjs' });
} catch (error) {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
} finally {
  vue.close();
}
