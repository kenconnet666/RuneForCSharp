#!/usr/bin/env node
// 从 vue-tsx-pro 的语言包（packages/ui/src/config/lang）生成三个库的 Lang（Config/Generated/Lang.g.cs）：
// 每条文案一个属性，带 lang.ts 里的说明；内置 ZhCn、EnUs；插值文案翻译成 C# 的 lambda（translate.mjs）。
// 用法：node tools/lang-gen/lang-gen.mjs [--check] [--vue <路径>]
import { parseArgs } from 'node:util';
import { LANG_PACKS, langMembers, langValues } from '../lib/lang.mjs';
import { writeOutputs } from '../lib/output.mjs';
import { openVue } from '../lib/vue.mjs';
import { pascal, Translator } from './translate.mjs';

/** 不移植的键：所在的能力不移植，或由别的机制负责 */
const SKIPPED = {
  errorCodes: '接口错误码的文案：桌面库不内置请求客户端（ROADMAP"平台化的约定"），应用自己的请求层按需要定义',
  formIssues: 'zod 的校验文案：三个库的校验走 INotifyDataErrorInfo / DataAnnotations，用它们自己的文案',
  messages: '页面级组件（主题编辑器、文档站组件）自带的文案表：做到这些组件时再定',
};

/** 三个库：命名空间与输出位置 */
const LIBRARIES = [
  { namespace: 'Rune.Avalonia', path: 'avalonia/src/Rune.Avalonia/Config/Generated/Lang.g.cs' },
  { namespace: 'Rune.Wpf', path: 'wpf/src/Rune.Wpf/Config/Generated/Lang.g.cs' },
  { namespace: 'Rune.WinForms', path: 'winforms/src/Rune.WinForms/Config/Generated/Lang.g.cs' },
];

const PACK_NAMES = { 'zh-CN': { id: 'ZhCn', summary: '简体中文（默认）' }, 'en-US': { id: 'EnUs', summary: '美国英语' } };

const escapeXml = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const docLines = (text, indent) => {
  const lines = escapeXml(text).split('\n').map((line) => line.trim()).filter(Boolean);
  return lines.length === 1 ? [`${indent}/// <summary>${lines[0]}</summary>`] : [`${indent}/// <summary>`, ...lines.map((line) => `${indent}/// ${line}`), `${indent}/// </summary>`];
};

/** 与命名空间无关的部分：属性声明与两份内置语言的初始化 */
function body(vue) {
  const translator = new Translator(vue.ast);
  const members = langMembers(vue).filter((member) => !SKIPPED[member.name]);
  const types = new Map(
    members.map((member) => {
      try {
        return [member.name, translator.type(member.type, member.source)];
      } catch (error) {
        throw new Error(`Lang.${member.name}：${error.message}`);
      }
    }),
  );
  const lines = [];
  for (const member of members) {
    const type = types.get(member.name);
    lines.push(...docLines(member.doc || member.name, '    '));
    lines.push(member.optional ? `    public ${translator.nullable(type).cs} ${pascal(member.name)} { get; init; }` : `    public required ${type.cs} ${pascal(member.name)} { get; init; }`, '');
  }
  for (const pack of LANG_PACKS) {
    const values = langValues(vue, pack);
    const { id, summary } = PACK_NAMES[pack.code];
    lines.push(`    /// <summary>${summary}。</summary>`, `    public static Lang ${id} { get; } = new()`, '    {');
    for (const member of members) {
      const entry = values.get(member.name);
      if (!entry) {
        if (member.optional) continue;
        throw new Error(`${pack.file} 缺少必填的 ${member.name}`);
      }
      try {
        lines.push(`        ${pascal(member.name)} = ${translator.value(types.get(member.name), entry.node, entry.source, '        ')},`);
      } catch (error) {
        throw new Error(`${pack.code} 的 ${member.name}：${error.message}`);
      }
    }
    lines.push('    };', '');
  }
  lines.pop();
  return lines;
}

function file(namespace, lines) {
  return [
    '// <auto-generated />',
    '// 由 tools/lang-gen 从 vue-tsx-pro 的 packages/ui/src/config/lang 生成，不要手改；改了那边的语言包后运行 node tools/lang-gen/lang-gen.mjs',
    // 标了 auto-generated 的文件默认不开可空注解，可选的文案（string?、double?）要显式打开
    '#nullable enable',
    'using System.Globalization;',
    '',
    `namespace ${namespace};`,
    '',
    '/// <summary>',
    '/// 语言包：组件里的文案与地区设置（vue-tsx-pro 的 Lang）。内置 <see cref="ZhCn"/>（默认）与 <see cref="EnUs"/>；',
    '/// 改几条用 <c>Lang.ZhCn with { Confirm = "好" }</c>。要插值的文案是函数：<c>lang.PaginationTotal(1286)</c>。',
    '/// 没有移植的键：',
    ...Object.entries(SKIPPED).map(([key, why]) => `/// <c>${key}</c>（${escapeXml(why)}）；`),
    '/// </summary>',
    'public sealed partial record Lang',
    '{',
    ...lines,
    '}',
    '',
  ].join('\n');
}

const { values: options } = parseArgs({
  options: {
    check: { type: 'boolean', default: false },
    vue: { type: 'string' },
  },
});

const vue = await openVue(options.vue);
try {
  const lines = body(vue);
  const outputs = LIBRARIES.map(({ namespace, path }) => ({ path, content: file(namespace, lines) }));
  process.exitCode = writeOutputs(outputs, { check: options.check, commit: vue.commit, command: 'node tools/lang-gen/lang-gen.mjs' });
} catch (error) {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
} finally {
  vue.close();
}

