#!/usr/bin/env node
// 从 vue-tsx-pro 的省市区数据（packages/ui/src/area/data.ts，取自 @vant/area-data，MIT）生成三个库的 AreaData（Utils/Data/Area/AreaData.g.cs）：
// 省、市、区县各一段"代码=名称;"的文本，Area 第一次用到时解析（几千项写成字典初始化会让程序集的 IL 大很多）。
// 用法：node tools/area-gen/area-gen.mjs [--check] [--vue <路径>]
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { writeOutputs } from '../lib/output.mjs';
import { openVue } from '../lib/vue.mjs';

const LIBRARIES = [
  { namespace: 'Rune.Avalonia', path: 'avalonia/src/Rune.Avalonia/Utils/Data/Area/AreaData.g.cs' },
  { namespace: 'Rune.Wpf', path: 'wpf/src/Rune.Wpf/Utils/Data/Area/AreaData.g.cs' },
  { namespace: 'Rune.WinForms', path: 'winforms/src/Rune.WinForms/Utils/Data/Area/AreaData.g.cs' },
];

const SECTIONS = [
  { key: 'province_list', name: 'Provinces', summary: '省级（6 位代码）' },
  { key: 'city_list', name: 'Cities', summary: '市级（6 位代码，前两位是省）' },
  { key: 'county_list', name: 'Counties', summary: '区县（6 位代码，前四位是市）' },
];

/** data.ts 里一段的条目：`110000: '北京市',` */
function entries(source, key) {
  const start = source.indexOf(`\n  ${key}: {`);
  if (start < 0) throw new Error(`area/data.ts 里找不到 ${key}`);
  const end = source.indexOf('\n  },', start);
  const items = [...source.slice(start, end).matchAll(/^\s*'?(\d{6})'?: '([^']*)',?$/gm)].map(([, code, name]) => [code, name]);
  if (items.length === 0) throw new Error(`area/data.ts 的 ${key} 是空的`);
  for (const [, name] of items) if (/[=;"\\]/.test(name)) throw new Error(`名称里有分隔符：${name}`);
  return items;
}

function file(namespace, sections) {
  return [
    '// <auto-generated>',
    '// 由 tools/area-gen/area-gen.mjs 从 vue-tsx-pro 的 packages/ui/src/area/data.ts 生成，不要手改。',
    '// 数据取自 @vant/area-data 2.2.0（Copyright (c) Youzan，MIT License），见 licenses/vant-area-data.txt。',
    '// </auto-generated>',
    '',
    `namespace ${namespace};`,
    '',
    '/// <summary>省市区的行政区划：每段是"代码=名称;"，由 <see cref="Area"/> 解析。</summary>',
    'static class AreaData',
    '{',
    ...sections.flatMap(({ name, summary, items }) => [
      `    /// <summary>${summary}。</summary>`,
      `    public const string ${name} = "${items.map(([code, label]) => `${code}=${label};`).join('')}";`,
      '',
    ]).slice(0, -1),
    '}',
    '',
  ].join('\n');
}

const { values: options } = parseArgs({ options: { check: { type: 'boolean', default: false }, vue: { type: 'string' } } });

const vue = await openVue(options.vue);
try {
  const source = readFileSync(join(vue.src, 'area/data.ts'), 'utf8');
  const sections = SECTIONS.map((section) => ({ ...section, items: entries(source, section.key) }));
  const outputs = LIBRARIES.map(({ namespace, path }) => ({ path, content: file(namespace, sections) }));
  process.exitCode = writeOutputs(outputs, { check: options.check, commit: vue.commit, command: 'node tools/area-gen/area-gen.mjs' });
} catch (error) {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
} finally {
  vue.close();
}
